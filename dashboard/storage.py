import os
import sqlite3
from pathlib import Path


SUPABASE_DB_URL_KEY = "SUPABASE_DB_URL"


class StorageError(RuntimeError):
    """Raised when an incident database operation fails."""


def is_supabase_configured() -> bool:
    return bool(os.environ.get(SUPABASE_DB_URL_KEY, "").strip())


def _database_error_types() -> tuple[type[Exception], ...]:
    errors: tuple[type[Exception], ...] = (sqlite3.Error,)
    if is_supabase_configured():
        import psycopg

        errors += (psycopg.Error,)
    return errors


def connect(database_path: Path | str, readonly: bool = False):
    database_url = os.environ.get(SUPABASE_DB_URL_KEY, "").strip()
    if database_url:
        try:
            import psycopg
        except ModuleNotFoundError as error:
            raise StorageError(
                "Supabase is configured, but the psycopg dependency is unavailable."
            ) from error
        try:
            return psycopg.connect(database_url, prepare_threshold=None)
        except psycopg.Error as error:
            raise StorageError("Could not connect to the Supabase database.") from error

    path = Path(database_path)
    try:
        if readonly:
            database_uri = f"{path.resolve().as_uri()}?mode=ro"
            return sqlite3.connect(database_uri, uri=True)
        return sqlite3.connect(path)
    except sqlite3.Error as error:
        raise StorageError(f"Could not open the incident database: {path}") from error


def execute(
    connection,
    sqlite_query: str,
    postgres_query: str,
    parameters: tuple = (),
):
    query = postgres_query if is_supabase_configured() else sqlite_query
    try:
        return connection.execute(query, parameters)
    except _database_error_types() as error:
        raise StorageError("Incident database query failed.") from error


def commit(connection) -> None:
    try:
        connection.commit()
    except _database_error_types() as error:
        raise StorageError("Could not commit incident database changes.") from error


def initialize_schema(database_path: Path | str) -> None:
    connection = connect(database_path)
    try:
        if is_supabase_configured():
            execute(
                connection,
                "",
                """
                CREATE TABLE IF NOT EXISTS incidents (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    timestamp TEXT NOT NULL,
                    incident_type TEXT NOT NULL,
                    camera_id TEXT NOT NULL,
                    camera_name TEXT NOT NULL,
                    zone_name TEXT NOT NULL DEFAULT '',
                    track_id TEXT,
                    extra_info TEXT,
                    review_status TEXT NOT NULL DEFAULT 'Pending',
                    reviewed_at TEXT
                )
                """,
            )
            execute(
                connection,
                "",
                "ALTER TABLE incidents ADD COLUMN IF NOT EXISTS "
                "review_status TEXT NOT NULL DEFAULT 'Pending'",
            )
            execute(
                connection,
                "",
                "ALTER TABLE incidents ADD COLUMN IF NOT EXISTS reviewed_at TEXT",
            )
        else:
            execute(
                connection,
                """
                CREATE TABLE IF NOT EXISTS incidents (
                    id            INTEGER PRIMARY KEY AUTOINCREMENT,
                    timestamp     TEXT    NOT NULL,
                    incident_type TEXT    NOT NULL,
                    camera_id     TEXT    NOT NULL,
                    camera_name   TEXT    NOT NULL,
                    zone_name     TEXT    NOT NULL DEFAULT '',
                    track_id      TEXT,
                    extra_info    TEXT,
                    review_status TEXT    NOT NULL DEFAULT 'Pending',
                    reviewed_at   TEXT
                )
                """,
                "",
            )
        commit(connection)
    finally:
        connection.close()
